#!/usr/bin/env node
// Historic rankings → burgundy-history.js
//
//   node tools/history-build.js [data/history/historic-class.json]
//
// The JSON holds, per source, the rank of each atlas climat (ids as in burgundy-data*.js and the INAO extras):
// Lavalle 1855 (read from the book), the Beaune committee of 1860 (via Danguy & Aubertin 1892, gaps from
// monocepage.com), Rodier 1920 (via monocepage.com's tables). Unmatched names stay in the JSON for reference.
"use strict";
const fs = require("fs"), path = require("path");
const ROOT = path.resolve(__dirname, ".."), src = process.argv[2] || path.join(ROOT, "data/history/historic-class.json");
const H = JSON.parse(fs.readFileSync(src, "utf8")), out = { sources: H.sources || {} };
["lavalle1855", "comite1860", "rodier1920"].forEach(k => {
  out[k] = Object.fromEntries(Object.entries(H[k] || {}).map(([id, v]) => [id, { rank: v.rank, as: v.as || "", note: v.note || "" }]));
});
fs.writeFileSync(path.join(ROOT, "burgundy-history.js"), "// Generated by tools/history-build.js — do not edit by hand.\nwindow.BURG_HISTORY = " + JSON.stringify(out) + ";\n");
console.log("wrote burgundy-history.js:", ["lavalle1855", "comite1860", "rodier1920"].map(k => `${k} ${Object.keys(out[k]).length}`).join(", "));
