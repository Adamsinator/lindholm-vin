#!/usr/bin/env node
// A region's owners, from its sourced list (data/owners/<id>.json) → atlas-<id>-own.js (shown by atlas-owners.js).
//
//   node tools/region-owners.js <region …>
//
// The list holds only what each domaine's own website says it owns, with the page it says it on: [domaine, hectares
// or null, url, what the page says]. The build refuses a climat the region's pack doesn't have, a domaine it doesn't
// name, a page that isn't on the web, and holdings that add up to more than the climat.
"use strict";
const fs = require("fs"), path = require("path");
const ROOT = path.resolve(__dirname, "..");
const ids = process.argv.slice(2); if (!ids.length) { console.error("usage: node tools/region-owners.js <region …>"); process.exit(1); }
for (const id of ids) {
  const D = JSON.parse(fs.readFileSync(path.join(ROOT, "data", "owners", id + ".json"), "utf8"));
  global.window = {}; require(path.join(ROOT, `atlas-${id}.js`)); const P = window.ATLAS_PACKS[id], byId = Object.fromEntries(P.climats.map(c => [c.id, c]));
  const errs = [], own = {};
  for (const [cid, rows] of Object.entries(D.holdings)) {
    const c = byId[cid]; if (!c) { errs.push(`${cid}: no such climat in atlas-${id}.js`); continue; }
    let sum = 0;
    own[cid] = rows.map(([k, ha, url, says]) => {
      if (!D.producers[k]) errs.push(`${cid}: ${k} isn't in producers`);
      if (!/^https:\/\/[^\s]+$/.test(url || "")) errs.push(`${cid}/${k}: no source page`);
      if (ha != null && !(ha > 0)) errs.push(`${cid}/${k}: area ${ha}`);
      sum += ha || 0; return [k, ha, url, says || ""];
    });
    if (sum > c.ha * 1.02) errs.push(`${cid}: holdings add up to ${sum.toFixed(2)} ha, more than the climat's ${c.ha} ha`);
  }
  if (errs.length) { console.error(errs.join("\n")); process.exit(1); }
  const out = { checked: D.checked, rule: D.rule, producers: Object.fromEntries(Object.entries(D.producers).map(([k, v]) => [k, [v.n, v.site]])), own };
  const js = `// Generated by tools/region-owners.js from data/owners/${id}.json — do not edit by hand.\n(window.ATLAS_OWN_DATA ||= {})[${JSON.stringify(id)}] = ${JSON.stringify(out)};\n`;
  fs.writeFileSync(path.join(ROOT, `atlas-${id}-own.js`), js);
  console.log(`${id}: ${Object.values(own).flat().length} holdings in ${Object.keys(own).length} climats, ${Object.keys(D.producers).length} domaines (${(js.length / 1024).toFixed(1)} KB)`);
}
