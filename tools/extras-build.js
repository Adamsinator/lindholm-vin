#!/usr/bin/env node
// Researched owners for the INAO premiers crus the atlas had no data for → burgundy-extras.js
//
//   node tools/extras-build.js [data/extras/extras-owners.json]
//
// Keeps holdings backed by a domaine, importer or specialist source (Inside Burgundy, Becky Wasserman, domaine
// sheets, the Hospices de Beaune sale…); "notable producers" lists that don't distinguish owners from négociants are
// left out. Only producers that keep at least one holding are written.
"use strict";
const fs = require("fs"), path = require("path");
const ROOT = path.resolve(__dirname, ".."), src = process.argv[2] || path.join(ROOT, "data/extras/extras-owners.json");
const X = JSON.parse(fs.readFileSync(src, "utf8"));
const WEAK = /sommelier-academy/i;
const holdings = {}, used = new Set(); let dropped = 0;
Object.entries(X.holdings || {}).forEach(([id, rows]) => {
  const keep = rows.filter(r => { const ok = !WEAK.test(r[3] || ""); if (!ok) dropped++; return ok; }).map(([k, h, kind]) => [k, h == null ? null : +h, kind || ""]);
  if (keep.length) { holdings[id] = keep; keep.forEach(([k]) => used.add(k)); }
});
const producers = Object.fromEntries(Object.entries(X.new_producers || {}).filter(([k]) => used.has(k)));
const out = { holdings, producers, notes: X.notes || {} };
fs.writeFileSync(path.join(ROOT, "burgundy-extras.js"), "// Generated by tools/extras-build.js — do not edit by hand.\nwindow.BURG_EXTRAS = " + JSON.stringify(out) + ";\n");
console.log(`wrote burgundy-extras.js: ${Object.keys(holdings).length} climats, ${Object.values(holdings).flat().length} holdings, ${Object.keys(producers).length} new producers, ${dropped} weak-source rows left out`);
