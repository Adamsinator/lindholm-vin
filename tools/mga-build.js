#!/usr/bin/env node
// Barolo's and Barbaresco's "menzioni geografiche aggiuntive" (MGA), the named vineyard areas a label may carry
// ("Barolo Cannubi"), read straight from the production rules (the disciplinari, as the Italian sommeliers'
// association AIS republishes them; the law's own text, not anyone's map) → ../piemonte-mga.js.
// No outlines: Regione Piemonte doesn't publish the MGA boundaries as open data, and the maps that exist (the
// Consorzio's, Masnaghetti's) are copyrighted. So this is names, aliases and the rules that go with them.
//
//   node tools/mga-build.js          (needs curl and pdftotext; the PDFs are cached in tools/.region-cache)
"use strict";
const fs = require("fs"), path = require("path"), { execFileSync } = require("child_process");
const ROOT = path.resolve(__dirname, ".."), CACHE = path.join(__dirname, ".region-cache"); fs.mkdirSync(CACHE, { recursive: true });

// where the list is (the article "Designazione e presentazione") and the rules worth showing, as the text states them
// (art. 2 grape, art. 4 yields, art. 5 ageing); checked against the PDF by hand, and tools/mga-test.js reads them back
const DOCG = {
  barolo: { name: "Barolo", url: "https://aisitalia.it/Disciplinari/Piemonte/DOCG/Barolo.pdf",
    rules: { grape: "Nebbiolo 100%", yield: 8, yieldVigna: 7.2, ageing: 38, wood: 18, riserva: 62 },
    communes: ["Barolo", "Castiglione Falletto", "Serralunga d'Alba", "Monforte d'Alba", "Novello", "La Morra", "Verduno", "Grinzane Cavour", "Diano d'Alba", "Cherasco", "Roddi"] },
  barbaresco: { name: "Barbaresco", url: "https://aisitalia.it/Disciplinari/Piemonte/DOCG/Barbaresco.pdf",
    rules: { grape: "Nebbiolo 100%", yield: 8, yieldVigna: 7.2, ageing: 26, wood: 9, riserva: 50 },
    communes: ["Barbaresco", "Neive", "Treiso", "Alba (San Rocco Seno d'Elvio)"] },
};

const slug = s => s.toLowerCase().normalize("NFD").replace(/[̀-ͯ]/g, "").replace(/[^a-z0-9]+/g, "_").replace(/^_|_$/g, "");
// the law writes a final accent as an apostrophe ("Rabaja'", "Paje'"); labels write the accent (Rabajà, Pajè).
// Not "Ca'": that apostrophe is real (ca' = casa, Ca' Grossa)
const accent = s => s.replace(/’/g, "'").replace(/\b(\w{3,}?)([aeiou])'(?=\s|$|-)/g, (m, w, v) => w + ({ a: "à", e: "è", i: "ì", o: "ò", u: "ù" })[v]);
// where the text itself slips, as printed in this edition: a missing comma, a misprint, an accent the law leaves off
const FIX = { "Gallaretto Garretti": ["Gallaretto", "Garretti"], "Manforte d'Alba": ["Monforte d'Alba"], "Rabaja-Bas": ["Rabajà-Bas"] };

function textOf(id) {
  const pdf = path.join(CACHE, `mga-${id}.pdf`), txt = pdf.replace(/\.pdf$/, ".txt");
  if (!fs.existsSync(pdf)) fs.writeFileSync(pdf, execFileSync("curl", ["-sS", "-L", "--max-time", "120", DOCG[id].url], { maxBuffer: 1 << 26 }));
  execFileSync("pdftotext", ["-layout", pdf, txt]);
  return fs.readFileSync(txt, "utf8");
}

function parse(id) {
  const t = textOf(id);
  const m = t.match(/«menzioni geografiche aggiuntive»,?\s+amministrativamente\s+definite\s+nell.allegato al presente disciplinare di produzione:\s*([\s\S]*?)\.\s*Le suddette menzioni/);
  if (!m) throw new Error(id + ": the list of menzioni wasn't found in the disciplinare");
  const raw = m[1].replace(/\s*\n\s*/g, " ").replace(/\s+/g, " ").replace(/- /g, "-").trim();
  // "a, b, …, y e z" (Barbaresco ends "Vallegrande e Vicenziana"; Barolo just with commas)
  const items = raw.replace(/’/g, "'").split(/,\s*/).flatMap((x, i, a) => i === a.length - 1 ? x.split(/\s+e\s+(?=[A-ZÀ-Ý])/) : [x]).map(x => x.trim()).filter(Boolean)
    .flatMap(x => { const v = x.match(/^(del comune di )(.+)$/); return v ? (FIX[v[2]] || [v[2]]).map(y => v[1] + y) : FIX[x] || [x]; });
  const mga = [], villages = [];
  for (const it of items) {
    const v = it.match(/^del comune di (.+)$/);
    if (v) { villages.push({ id: slug("comune " + v[1]), n: v[1], official: it }); continue; }
    // "Cannubi Boschis o Cannubi", "Altenasso o Garblet Suè o Garbelletto Superiore": the first is the MGA, the
    // others names it may also go by
    const [n, ...aka] = it.split(/\s+o\s+/).map(x => x.trim());
    mga.push(Object.assign({ id: slug(accent(n)), n: accent(n) }, accent(n) !== n ? { official: n } : {}, aka.length ? { aka: aka.map(accent) } : {}));
  }
  return { mga, villages };
}

const out = { built: new Date().toISOString().slice(0, 10),
  source: "Disciplinari di produzione DOCG Barolo e Barbaresco (art. 8 and art. 7), as republished by AIS (aisitalia.it)", docg: {} };
for (const id of Object.keys(DOCG)) {
  const { mga, villages } = parse(id), D = DOCG[id];
  out.docg[id] = { name: D.name, rules: D.rules, communes: D.communes, mga, villages };
  console.error(`${D.name}: ${mga.length} MGA, ${villages.length} village mentions, ${mga.filter(x => x.aka).length} with other names`);
}
fs.writeFileSync(path.join(ROOT, "piemonte-mga.js"), `// Generated by tools/mga-build.js — do not edit by hand.\nwindow.PIEMONTE_MGA = ${JSON.stringify(out)};\n`);
