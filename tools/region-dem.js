#!/usr/bin/env node
// Measured altitude, slope and aspect for each vineyard of a French region pack → atlas-<id>-dem.js
//
//   node tools/region-dem.js chablis [rhone …]      (or "all"; needs atlas-<id>.js; uses curl and IGN's elevation service)
//
// As tools/dem-import.js does for the Côte d'Or: IGN's RGE ALTI® (1–5 m terrain model) sampled on a grid inside each
// outline (dem-lib.js), local gradients between neighbouring samples giving the mean slope and the way it faces.
// Output per vineyard id: [alt low (p5), alt high (p95), mean alt, slope %, aspect ° (0 = N, 90 = E), consistency %,
// samples, grid step m]. On a big appellation (Saint-Émilion, 7 000 ha) the grid is hundreds of metres apart, so its
// slope is the lie of the land between samples, not the steepness of a single row; atlas.js says so.
// Responses are cached in tools/.dem-cache.
"use strict";
const fs = require("fs"), path = require("path");
const ROOT = path.resolve(__dirname, ".."), CACHE = path.join(__dirname, ".dem-cache"); fs.mkdirSync(CACHE, { recursive: true });
const FRENCH = ["chablis", "chalonnaise", "maconnais", "champagne", "alsace", "rhone", "bordeaux", "beaujolais", "rhonesud", "centreloire", "touraine", "anjou"];

// Lambert-93 (EPSG:2154) back to longitude and latitude: the inverse of the conformal conic in atlas.js
const a = 6378137, e = 0.0818191910428158, d = Math.PI / 180;
const m = p => Math.cos(p) / Math.sqrt(1 - e * e * Math.sin(p) ** 2), tt = p => Math.tan(Math.PI / 4 - p / 2) / ((1 - e * Math.sin(p)) / (1 + e * Math.sin(p))) ** (e / 2);
const n = (Math.log(m(44 * d)) - Math.log(m(49 * d))) / (Math.log(tt(44 * d)) - Math.log(tt(49 * d))), F = m(44 * d) / (n * tt(44 * d) ** n), r0 = a * F * tt(46.5 * d) ** n;
const L93 = (lon, lat) => { const r = a * F * tt(lat * d) ** n, th = n * (lon - 3) * d; return [700000 + r * Math.sin(th), 6600000 + r0 - r * Math.cos(th)]; };
function L93inv(E, N) {
  const dx = E - 700000, dy = r0 - (N - 6600000), r = Math.hypot(dx, dy), th = Math.atan2(dx, dy), t = (r / (a * F)) ** (1 / n);
  let p = Math.PI / 2 - 2 * Math.atan(t);
  for (let i = 0; i < 8; i++) p = Math.PI / 2 - 2 * Math.atan(t * ((1 - e * Math.sin(p)) / (1 + e * Math.sin(p))) ** (e / 2));
  return [th / n / d + 3, p / d];
}
{ const [E, N] = L93(4.8, 46.3), [lo, la] = L93inv(E, N); if (Math.abs(lo - 4.8) > 1e-9 || Math.abs(la - 46.3) > 1e-9) throw new Error("Lambert-93 round trip"); }

const inRing = (x, y, r) => { let c = false; for (let i = 0, j = r.length - 1; i < r.length; j = i++) { const [xi, yi] = r[i], [xj, yj] = r[j]; if ((yi > y) !== (yj > y) && x < (xj - xi) * (y - yi) / (yj - yi) + xi) c = !c; } return c; };
const inPoly = (x, y, mp) => mp.some(p => inRing(x, y, p[0]) && !p.slice(1).some(h => inRing(x, y, h)));
const area = r => Math.abs(r.reduce((s, [x, y], i) => { const [x2, y2] = r[(i + 1) % r.length]; return s + x * y2 - x2 * y; }, 0) / 2);

async function build(id) {
  global.window = {}; require(path.join(ROOT, `atlas-${id}.js`));
  const P = window.ATLAS_PACKS[id], [E0, N0] = P.meta.l93;
  if (!E0 || P.meta.proj) throw new Error(id + ": not a Lambert-93 pack");
  // the pack's y grows southwards; dem-lib wants y northwards (its aspect is atan2(east, north)), so flip it here
  const north = mp => mp.map(p => p.map(r => r.map(([x, y]) => [x, -y])));
  const toLL = ([x, yN]) => L93inv(E0 + x, N0 + yN);
  const { elev, stats, grid } = require("./dem-lib.js")(CACHE, toLL);
  const jobs = P.climats.map(c => ({ id: c.id, ...grid(north(c.g), inPoly, area, 80, 160) })).filter(j => j.pts.length >= 3);
  console.log(`${id}: ${jobs.length} vineyards, ${jobs.reduce((s, j) => s + j.pts.length, 0)} sample points`);
  const out = {}; let i = 0;
  await Promise.all(Array.from({ length: 6 }, async () => {
    while (i < jobs.length) { const { id: cid, pts, step } = jobs[i++], r = stats(pts, step, await elev(`${id}-${cid}`, pts)); if (r) out[cid] = r.concat(Math.round(step)); }
  }));
  const meta = { id, source: "IGN — RGE ALTI® via the Géoplateforme altimetry service (Licence Ouverte)", built: new Date().toISOString().slice(0, 10),
    fields: ["alt low (p5, m)", "alt high (p95, m)", "mean alt (m)", "mean slope %", "aspect ° (faces; 0 = N, 90 = E)", "aspect consistency %", "samples", "grid step (m)"] };
  fs.writeFileSync(path.join(ROOT, `atlas-${id}-dem.js`), `// Generated by tools/region-dem.js ${id} — do not edit by hand.\nwindow.ATLAS_DEM = window.ATLAS_DEM || {};\nwindow.ATLAS_DEM[${JSON.stringify(id)}] = ${JSON.stringify({ meta, c: out })};\n`);
  const show = P.climats.filter(c => out[c.id]).sort((x, y) => (x.c === "GC" ? 0 : 1) - (y.c === "GC" ? 0 : 1)).slice(0, 4);
  console.log(`  wrote atlas-${id}-dem.js: ${Object.keys(out).length}/${P.climats.length}; ` + show.map(c => `${c.n} ${out[c.id].slice(0, 5).join("/")}`).join(" · "));
}

(async () => {
  const ids = process.argv.slice(2); if (!ids.length) { console.error("usage: node tools/region-dem.js <region…|all>"); process.exit(1); }
  for (const id of ids[0] === "all" ? FRENCH : ids) await build(id);
})().catch(err => { console.error(err.message); process.exit(1); });
