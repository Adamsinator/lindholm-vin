#!/usr/bin/env node
// Vintage history for the atlas → burgundy-vintages.js
//
//   node tools/vintages-build.js <vintages.json> <vintage-weather.json> [vintages-i18n.json]
//
// vintages.json: the researched vintage ratings (consensus score per Côte and colour, character note, drink window,
// the published charts it rests on), harvest dates, crop notes and dated weather events with the communes they hit.
// vintage-weather.json: Météo-France station metrics from tools/vintage-weather.js.
// Event areas are matched to the atlas's communes by name ("Volnay", "Chambolle-Musigny", "Côte de Beaune"…);
// anything unmatched is listed and dropped.
"use strict";
const fs = require("fs"), path = require("path");
const ROOT = path.resolve(__dirname, "..");
const [vf, wf, tf] = process.argv.slice(2);
const R = JSON.parse(fs.readFileSync(vf, "utf8")), Wx = JSON.parse(fs.readFileSync(wf, "utf8"));
global.window = {};
["burgundy-data.js", "burgundy-data-beaune.js"].forEach(f => require(path.join(ROOT, f)));
const { villages: V, cotes } = window.BURG;
{ let cur = cotes[0].id; V.forEach(v => { const k = cotes.find(x => x.first === v.id); if (k) cur = k.id; v.cote = cur; }); }

const norm = t => String(t || "").toLowerCase().normalize("NFD").replace(/[̀-ͯ]/g, "").replace(/[-'’]/g, " ").replace(/\bst\b/g, "saint").replace(/\s+/g, " ").trim();
const byName = {};
V.forEach(v => v.n.split(" · ").forEach(p => { byName[norm(p)] = v.id; byName[norm(p.split(/[- ]/)[0])] ??= v.id; }));
Object.assign(byName, { "ladoix": "corton", "aloxe corton": "corton", "pernand vergelesses": "corton", "corton": "corton", "auxey duresses": "monthelie",
  "flagey echezeaux": "flagey", "premeaux prissey": "premeaux", "premeaux": "premeaux", "echezeaux": "flagey", "saint romain": "monthelie", "blagny": "meursault" });
const unmatched = new Set();
function villagesOf(areas) {
  const out = new Set();
  (areas || []).forEach(a => {
    const n = norm(a);
    if (/cote de nuits|nuits villages|cote d ?or|cote dor|whole|all of/.test(n) && !/beaune/.test(n)) V.filter(v => v.cote === "nuits" || /cote d ?or|cote dor|whole|all of/.test(n)).forEach(v => out.add(v.id));
    if (/cote de beaune|cote d ?or|cote dor|whole|all of/.test(n)) V.filter(v => v.cote === "beaune").forEach(v => out.add(v.id));
    if (/cote/.test(n)) return;
    const hit = byName[n] || byName[n.replace(/^(vineyards of|parts of|the) /, "")] || Object.keys(byName).find(k => k.length > 4 && n.includes(k)) && byName[Object.keys(byName).find(k => k.length > 4 && n.includes(k))];
    if (hit) out.add(hit); else unmatched.add(a);
  });
  return [...out];
}

const CATS = ["nuits_red", "beaune_red", "beaune_white"], years = {};
Object.entries(R.vintages || {}).forEach(([y, v]) => {
  const o = years[y] = {};
  CATS.forEach(k => { const c = v[k]; if (c && c.score != null) o[k] = [Math.round(c.score), c.estimate ? 1 : 0, c.note || "", c.drink || "", (c.sources || []).map(s => [s.source, s.value, s.scale, s.url])]; });
  if (v.harvest_start) o.harvest = v.harvest_start;
  if (v.crop) o.crop = v.crop;
});
Object.entries(Wx.years).forEach(([y, w]) => { if (+y >= 1980) (years[y] ||= {}).wx = w; });
const events = (R.events || []).map(e => ({ d: e.date, t: e.type, a: e.areas || [], v: villagesOf(e.areas), s: e.severity || "", u: e.url || "" })).filter(e => e.d && e.v.length);
// translations of the notes, keyed by the English text: {da:{notes:{en:da}}, fr:{…}}
const i18n = tf ? Object.fromEntries(Object.entries(JSON.parse(fs.readFileSync(tf, "utf8"))).map(([l, v]) => [l, v.notes || v])) : {};
const out = { i18n, meta: { built: new Date().toISOString().slice(0, 10), method: R.method || "", weather: Wx.meta,
  cats: { nuits_red: "Côte de Nuits red", beaune_red: "Côte de Beaune red", beaune_white: "Côte de Beaune white" } }, years, events };
fs.writeFileSync(path.join(ROOT, "burgundy-vintages.js"), "// Generated by tools/vintages-build.js — do not edit by hand.\nwindow.BURG_VINTAGES = " + JSON.stringify(out) + ";\n");
const scored = Object.values(years).filter(y => CATS.some(k => y[k])).length;
console.log(`wrote burgundy-vintages.js: ${scored} rated vintages, ${Object.keys(years).length} years with weather, ${events.length} events`);
if (unmatched.size) console.log("event areas not matched to a commune:", [...unmatched].join("; "));
