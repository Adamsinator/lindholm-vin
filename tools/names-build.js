#!/usr/bin/env node
// INAO's other premiers crus and Corton climats (the atlas's "extras") as a small name list → burgundy-names.js
//
//   node tools/names-build.js        (after tools/inao-import.js)
//
// The cellar app uses it, with burgundy-data*.js, to recognise a climat on a label and suggest the wine's
// classification, without loading the 700 KB of outlines in burgundy-geo.js.
"use strict";
const fs = require("fs"), path = require("path");
const ROOT = path.resolve(__dirname, "..");
global.window = {};
require(path.join(ROOT, "burgundy-geo.js"));
const X = window.BURG_GEO.extra || {};
const climats = Object.entries(X).map(([id, x]) => [id, x.n, x.c, x.v, x.in ? 1 : 0]);
fs.writeFileSync(path.join(ROOT, "burgundy-names.js"), "// Generated by tools/names-build.js — do not edit by hand.\nwindow.BURG_NAMES = "
  + JSON.stringify({ built: new Date().toISOString().slice(0, 10), fields: ["id", "name", "class", "village", "inside another climat"], climats }) + ";\n");
console.log(`wrote burgundy-names.js: ${climats.length} climats`);
